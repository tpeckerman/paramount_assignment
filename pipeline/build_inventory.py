#!/usr/bin/env python3
"""Generate sources/00_SOURCE_INVENTORY.md from the manifest.

The inventory used to be maintained by hand and drifted 28 commits behind. By then it still
listed the retired Ofcom URL pattern that had already been fixed in the manifest, and it was
missing two Code sections added later. A stale index is worse than no index, because a reader
trusts it and follows a dead link instead of checking the live table.

So it is generated now. MANIFEST.csv, expect.json and NOTES.md are the source of truth; this
file is a view of them. CI regenerates it and fails if the committed copy differs, which is
the same guard already used on the CSV mirrors of the rules table.
"""
from __future__ import annotations

import csv
import json
import pathlib
import sys

import sys
sys.path.insert(0, str(__import__('pathlib').Path(__file__).resolve().parent))
import constants as C

ROOT = C.ROOT
ORIG = C.ORIGINALS_DIR
OUT = C.SOURCE_INVENTORY_MD

RANK = {
    "1": ("statute", "Primary legislation or directive. Sets the duty, rarely the detail."),
    "2": ("regulator_binding", "The regulator's own binding code, recommendation or "
                               "deliberation. This is the operative layer."),
    "3": ("regulator_guidance", "Guidance on how the regulator applies its own rules. Not "
                                "binding itself, but it is how the regulator reasons, and it "
                                "carries the worked examples."),
    "4": ("precedent", "Published enforcement decisions. Shows where thresholds actually sat."),
    "5": ("regulator_summary", "The regulator's plain-language web pages. Useful, but has "
                               "been wrong before (see conflict C-01)."),
    "6": ("classification_body", "Film classification bodies. Not TV regulators; relevant "
                                 "only as an input when the content is a theatrical film."),
    "7": ("secondary", "Government pages and commentary. Corroboration only, never cited "
                       "alone for a rule."),
}


def main() -> int:
    if "--help" in sys.argv or "-h" in sys.argv:
        print(__doc__)
        return 0
    rows = list(csv.DictReader((ORIG / "MANIFEST.csv").open(newline="", encoding="utf-8")))
    expect = json.loads((ORIG / "expect.json").read_text(encoding="utf-8"))["expect"]
    rules = list(csv.DictReader(C.RULES_CSV.open(
        newline="", encoding="utf-8")))

    used: dict[str, int] = {}
    for r in rules:
        for tok in r["source_doc"].replace("+", " ").split():
            used[tok.strip()] = used.get(tok.strip(), 0) + 1

    verified = sum(1 for r in rows if r["download_status"] == "verified")
    L = [
        "# Source inventory",
        "",
        "**Generated by `pipeline/build_inventory.py`. Do not edit by hand.**",
        "",
        "This file used to be maintained manually and drifted 28 commits out of date, still",
        "listing a retired URL pattern that had already been fixed and missing two Code",
        "sections. A stale index is worse than none, because a reader trusts it. It is now a",
        "view of `MANIFEST.csv`, and CI fails if the committed copy does not match.",
        "",
        f"**{len(rows)} documents, {verified} collected and verified on disk.** Scope is linear",
        "broadcast television in the UK and France. On-demand and streaming are a different",
        "regime in both countries and are out of scope.",
        "",
        "## Reading `rank`",
        "",
        "Used to resolve contradictions between sources. Lower number wins.",
        "",
        "| Rank | Type | What it means |",
        "|---|---|---|",
    ]
    for k, (name, meaning) in RANK.items():
        L.append(f"| {k} | `{name}` | {meaning} |")

    for country, title in (("UK", "United Kingdom"), ("FR", "France"), ("EU", "European Union")):
        sel = [r for r in rows if r["country"] == country]
        if not sel:
            continue
        L += ["", f"## {title}", "",
              "| id | Document | Rank | Rules | Status | URL |", "|---|---|---|---|---|---|"]
        for r in sel:
            n = used.get(r["doc_id"], 0)
            cites = str(n) if n else "_none_"
            ok = "verified" if r["download_status"] == "verified" else "**missing**"
            L.append(f"| `{r['doc_id']}` | {r['title']} | {r['tier'][:3]} | {cites} | {ok} "
                     f"| {r['url']} |")

    nocite = [r["doc_id"] for r in rows if not used.get(r["doc_id"])]
    L += [
        "",
        "## Documents no rule cites",
        "",
        f"`{'`, `'.join(nocite)}`" if nocite else "_None._",
        "",
        "This is not necessarily a gap. Some sources are background: they explain why a",
        "framework has its present shape without stating any operative rule. Others are",
        "corroboration for a rule sourced primarily elsewhere. What matters is that the list is",
        "visible, so nobody assumes a document is doing work it is not.",
        "",
        "## Verification",
        "",
        "Every document carries a phrase in `expect.json` that must appear in the stored file.",
        "It is checked on fetch, on manual import, and on every `--check`. This is the guard",
        "that caught a saved page containing 12,493 characters of pure site navigation, which",
        "had passed a length test.",
        "",
        "Each phrase has to identify its own document. Several earlier ones did not: one",
        "matched five files at once, and one matched only the wrong document, because two",
        "unrelated guidance notes both happened to say \"Issue Six\".",
        "",
        "See `sources/originals/NOTES.md` for what is known about individual sources, including",
        "which are translations, which are landing pages rather than the document itself, and",
        "which relate to a channel that no longer broadcasts.",
        "",
    ]
    text = "\n".join(L)

    if "--check" in sys.argv:
        if OUT.exists() and OUT.read_text(encoding="utf-8") == text:
            print("inventory is current")
            return 0
        print("inventory is STALE: regenerate with pipeline/build_inventory.py", file=sys.stderr)
        return 1

    OUT.write_text(text, encoding="utf-8")
    print(f"wrote {OUT.relative_to(ROOT)}  ({len(rows)} documents, {verified} verified, "
          f"{len(nocite)} cited by no rule)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
